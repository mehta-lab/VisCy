#!/usr/bin/env python
"""Re-tokenize ER/mito deconv-provenance prediction dirs to canonical raw form.

This is the *reverse* of the Phase-7 forward migration (``run_migration.py``): the
forward migration tagged pre-flip ER/mito A549/joint predictions with a
deconv-provenance ``train_set`` token, but after the A549 raw-regen + retrain
campaign those same models were re-predicted from RAW data. Their on-disk
``train_set`` component is now mislabeled and must drop the deconv marker::

    <organelle>/<model>/a549__deconv/<test>[__cond]/prediction.zarr
        -> <organelle>/<model>/a549/<test>[__cond]/prediction.zarr
    <organelle>/<model>/joint__legacy_deconvgt/<test>[__cond]/prediction.zarr
        -> <organelle>/<model>/joint/<test>[__cond]/prediction.zarr

Only ``er/`` and ``mito/`` are touched (deconv provenance is ER/mito-only per
:data:`dynacell.evaluation.paths` — ``__deconv`` is invalid for nucleus/membrane).
iPSC ``train_set`` dirs are already canonical and left alone. The rename happens
at the ``train_set`` directory component as a whole-directory rename, so the
``<test>[__cond]`` leaves and the ``prediction.zarr`` store contents travel
untouched.

The tool ALSO rewrites predict-leaf YAML ``output_store`` values that point at a
re-tokenized dir, so a re-predict / eval reads the renamed path. The rewrite is
tied to the same rule + exclude list that drives the dir moves (rewrite-iff-migrated),
so configs and disk stay consistent by construction. Eval leaves are *not* touched
here — they are regenerated by the grouped/instance-AP generators.

Safety model (mirrors the forward ``run_migration.py``)
-------------------------------------------------------
* **Dry-run by default.** ``--apply`` is required to touch disk.
* **Journaled.** Every executed dir rename and config edit is appended (one JSONL
  record per op, flushed per op) to a journal file as it is performed, so a crash
  leaves a complete record. ``--rollback <journal>`` replays it in reverse.
* **Collision guard.** A dir move whose destination already exists aborts the whole
  run before any mutation, naming every clashing destination — never a clobber.
* **Live-writer guard.** ``--skip <path>`` excludes a dir from BOTH its move and its
  config edit (use for a dir with an active SLURM writer). Detecting a live writer
  from a tool is unreliable, so the exclude list is the contract; ``--warn-recent-min
  N`` additionally prints a (non-blocking) warning for any planned dir touched within
  the last ``N`` minutes as a backstop.
* **Idempotent.** ``plan_dir_moves`` only finds still-old dirs and ``plan_config_edits``
  only finds still-old values, so a re-run after a partial/interrupted apply resumes
  cleanly (already-moved dirs / already-rewritten configs are skipped).
"""

from __future__ import annotations

import argparse
import datetime
import errno
import json
import sys
from dataclasses import dataclass
from pathlib import Path

from dynacell.evaluation.paths import DATA_ROOT

# train_set token renames (ER/mito predictions only). Mirrors the deconv-provenance
# tokens in ``dynacell.evaluation.paths``: ``a549__deconv`` (forward deconv A549
# token) and ``joint__legacy_deconvgt`` (the closed legacy-joint marker) -> their
# canonical RAW counterparts ``a549`` / ``joint``.
RETOKENIZE: dict[str, str] = {
    "a549__deconv": "a549",
    "joint__legacy_deconvgt": "joint",
}

# Deconv provenance is ER/mito-only; nucleus/membrane train_set dirs are already raw.
ORGANELLES: tuple[str, ...] = ("er", "mito")

# Predict-leaf key whose value points at a prediction store. Confirmed the only
# path key carrying the train_set token in hand-authored predict leaves
# (``trainer.callbacks[…HCSPredictionWriter].init_args.output_store``).
PREDICT_OUTPUT_KEY: str = "output_store"

# Default config tree scanned for predict-leaf output_store edits.
_DEFAULT_CONFIG_ROOT: Path = Path(__file__).resolve().parents[1] / "configs"


@dataclass(frozen=True)
class DirMove:
    """One planned whole-directory rename of a ``train_set`` dir.

    Attributes
    ----------
    organelle : str
        ``er`` or ``mito``.
    model : str
        Model code-key directory name (e.g. ``celldiff_r2``).
    src : Path
        ``<data_root>/<organelle>/<model>/<old_train_set>``.
    dst : Path
        ``<data_root>/<organelle>/<model>/<new_train_set>``.
    """

    organelle: str
    model: str
    src: Path
    dst: Path


@dataclass(frozen=True)
class ConfigEdit:
    """One planned predict-leaf ``output_store`` rewrite.

    Attributes
    ----------
    path : Path
        The predict-leaf YAML file.
    old_value : str
        The current ``output_store`` value (deconv-tokened).
    new_value : str
        The rewritten value (raw-tokened).
    """

    path: Path
    old_value: str
    new_value: str


def _now() -> str:
    """Return an ISO-8601 second-resolution timestamp."""
    return datetime.datetime.now().isoformat(timespec="seconds")


def _is_excluded(src: Path, skips: list[str]) -> bool:
    """Return True if ``src`` matches any ``--skip`` entry.

    A skip entry matches either the absolute src path, the
    ``<organelle>/<model>/<train_set>`` tail, or any trailing path fragment of
    ``src`` (so ``--skip mito/celldiff_r2/a549__deconv`` and the full absolute path
    both work).
    """
    src_str = str(src)
    tail = "/".join(src.parts[-3:])
    for raw in skips:
        s = raw.rstrip("/")
        if s in (src_str, tail) or src_str.endswith("/" + s):
            return True
    return False


def plan_dir_moves(data_root: Path, organelles: tuple[str, ...], skips: list[str]) -> list[DirMove]:
    """Enumerate the ER/mito ``train_set`` dirs to re-tokenize (read-only scan).

    Scans ``<data_root>/<organelle>/<model>/<train_set>`` and returns a move for
    every existing ``train_set`` dir whose name is a :data:`RETOKENIZE` key and that
    is not excluded by ``skips``. Idempotent: already-renamed (raw) dirs never match.

    Parameters
    ----------
    data_root : Path
        Prediction data root (``DATA_ROOT``).
    organelles : tuple of str
        Organelle roots to scan (``("er", "mito")``).
    skips : list of str
        ``--skip`` exclude entries.

    Returns
    -------
    list of DirMove
        Sorted by src path.
    """
    moves: list[DirMove] = []
    for organelle in organelles:
        org_root = data_root / organelle
        if not org_root.is_dir():
            continue
        for model_dir in sorted(p for p in org_root.iterdir() if p.is_dir()):
            for old_token, new_token in RETOKENIZE.items():
                src = model_dir / old_token
                if not src.is_dir():
                    continue
                if _is_excluded(src, skips):
                    continue
                moves.append(
                    DirMove(
                        organelle=organelle,
                        model=model_dir.name,
                        src=src,
                        dst=model_dir / new_token,
                    )
                )
    return sorted(moves, key=lambda m: str(m.src))


def _parse_pred_store(value: str, data_root: Path) -> tuple[str, str, str, tuple[str, ...]] | None:
    """Split a prediction-store path into ``(organelle, model, train_set, tail)``.

    Returns ``None`` if the value is not under ``data_root`` or is too short to be a
    ``<organelle>/<model>/<train_set>/<leaf>/...`` store path.
    """
    try:
        rel = Path(value).relative_to(data_root)
    except ValueError:
        return None
    parts = rel.parts
    if len(parts) < 4:
        return None
    return parts[0], parts[1], parts[2], parts[3:]


def _iter_output_store_values(yaml_path: Path) -> list[str]:
    """Return every ``output_store:`` scalar value in a YAML file (text scan).

    A deliberately dependency-free line scan (no YAML round-trip) so comments and
    anchors are preserved by the later exact-substring rewrite.
    """
    values: list[str] = []
    for line in yaml_path.read_text().splitlines():
        stripped = line.strip()
        prefix = f"{PREDICT_OUTPUT_KEY}:"
        if stripped.startswith(prefix):
            value = stripped[len(prefix) :].strip()
            if value:
                values.append(value)
    return values


def plan_config_edits(
    config_roots: list[Path],
    data_root: Path,
    organelles: tuple[str, ...],
    skips: list[str],
) -> list[ConfigEdit]:
    """Enumerate predict-leaf ``output_store`` rewrites tied to the move rule.

    Scans every ``*.yml`` / ``*.yaml`` under ``config_roots`` for ``output_store``
    values that point at an ER/mito deconv ``train_set`` dir (same rule + exclude
    list as :func:`plan_dir_moves`) and returns the rewrite to the raw token.
    Idempotent: already-raw values never match.

    Parameters
    ----------
    config_roots : list of Path
        Config trees to scan.
    data_root : Path
        Prediction data root (to interpret store paths).
    organelles : tuple of str
        Organelles in scope.
    skips : list of str
        Exclude entries (a config whose target dir is skipped is not rewritten).

    Returns
    -------
    list of ConfigEdit
        Sorted by (path, old_value).
    """
    edits: list[ConfigEdit] = []
    for root in config_roots:
        if not root.exists():
            continue
        for yaml_path in sorted({*root.rglob("*.yml"), *root.rglob("*.yaml")}):
            for value in _iter_output_store_values(yaml_path):
                parsed = _parse_pred_store(value, data_root)
                if parsed is None:
                    continue
                organelle, model, train_set, tail = parsed
                if organelle not in organelles or train_set not in RETOKENIZE:
                    continue
                src = data_root / organelle / model / train_set
                if _is_excluded(src, skips):
                    continue
                new_value = str(data_root / organelle / model / RETOKENIZE[train_set] / Path(*tail))
                edits.append(ConfigEdit(path=yaml_path, old_value=value, new_value=new_value))
    return sorted(edits, key=lambda e: (str(e.path), e.old_value))


def _existing_ancestor(path: Path) -> Path:
    """Return the nearest existing ancestor of ``path`` (for the same-device check)."""
    p = path
    while not p.exists():
        if p.parent == p:
            return p
        p = p.parent
    return p


def preflight_moves(moves: list[DirMove]) -> tuple[list[DirMove], list[DirMove], list[str]]:
    """Classify dir moves and collect blocking errors.

    Returns ``(pending, already, errors)``. ``pending`` are src-present /
    dest-absent renames to run; ``already`` are idempotent no-ops (src gone, dst
    present). ``errors`` blocks the whole run: a pre-existing destination
    (collision), a cross-device rename, a nested src/dest namespace, a duplicate
    destination, or a lost dir (neither src nor dst).
    """
    pending: list[DirMove] = []
    already: list[DirMove] = []
    errors: list[str] = []

    srcs = {m.src for m in moves}
    dests = {m.dst for m in moves}
    for d in dests:
        for s in srcs:
            if d == s or s in d.parents or d in s.parents:
                errors.append(f"NESTED src/dest: src={s} <-> dest={d}")

    seen_dest: dict[Path, Path] = {}
    for m in moves:
        if m.dst in seen_dest and seen_dest[m.dst] != m.src:
            errors.append(f"DEST COLLISION {m.dst} <- {seen_dest[m.dst]} and {m.src}")
        seen_dest[m.dst] = m.src

        src_exists = m.src.exists()
        dst_exists = m.dst.exists()
        if src_exists and not dst_exists:
            src_dev = m.src.stat().st_dev
            dst_dev = _existing_ancestor(m.dst).stat().st_dev
            if src_dev != dst_dev:
                errors.append(f"CROSS-DEVICE (rename unsafe) src={m.src} dest={m.dst}")
            else:
                pending.append(m)
        elif not src_exists and dst_exists:
            already.append(m)
        elif src_exists and dst_exists:
            errors.append(f"DEST EXISTS (collision — would clobber) src={m.src} dest={m.dst}")
        else:
            errors.append(f"SRC MISSING and DEST ABSENT (lost?) src={m.src} dest={m.dst}")
    return pending, already, errors


def _warn_recent(moves: list[DirMove], minutes: int) -> list[str]:
    """Return warnings for planned dirs touched within ``minutes`` (bounded scan).

    Checks only the src dir and its immediate children (no deep walk over huge zarr
    trees) — a cheap backstop for the ``--skip`` live-writer guard. Non-blocking.
    """
    if minutes <= 0:
        return []
    cutoff = datetime.datetime.now().timestamp() - minutes * 60
    warnings: list[str] = []
    for m in moves:
        if not m.src.exists():
            continue
        mtimes = [m.src.stat().st_mtime]
        mtimes.extend(c.stat().st_mtime for c in m.src.iterdir())
        if max(mtimes) >= cutoff:
            warnings.append(f"RECENTLY MODIFIED (<{minutes}m) — possible live writer, consider --skip: {m.src}")
    return warnings


def _append_journal(journal: Path, record: dict) -> None:
    """Append one JSONL record to the journal, flushing per op (crash-complete)."""
    with journal.open("a") as fh:
        fh.write(json.dumps({"ts": _now(), **record}) + "\n")


def apply_moves(pending: list[DirMove], journal: Path, dry_run: bool) -> int:
    """Execute (or preview) the pending dir renames, journaling each. Returns count applied."""
    applied = 0
    for m in pending:
        if dry_run:
            print(f"  [dry-run] move {m.organelle}/{m.model}: {m.src.name} -> {m.dst.name}")
            print(f"            {m.src}\n            -> {m.dst}")
            continue
        try:
            m.src.rename(m.dst)
        except OSError as exc:
            _append_journal(
                journal,
                {
                    "op": "dir_move",
                    "src": str(m.src),
                    "dst": str(m.dst),
                    "result": "error",
                    "detail": f"{type(exc).__name__}: {exc}",
                },
            )
            if exc.errno == errno.EXDEV:
                raise RuntimeError(f"cross-device rename despite pre-flight; src={m.src} dest={m.dst}") from exc
            raise
        _append_journal(journal, {"op": "dir_move", "src": str(m.src), "dst": str(m.dst), "result": "applied"})
        applied += 1
        print(f"  moved {m.organelle}/{m.model}: {m.src.name} -> {m.dst.name}")
    return applied


def apply_config_edits(edits: list[ConfigEdit], journal: Path, dry_run: bool) -> int:
    """Execute (or preview) the predict-leaf ``output_store`` rewrites. Returns count applied."""
    applied = 0
    for e in edits:
        if dry_run:
            print(f"  [dry-run] edit {e.path}\n            {e.old_value}\n            -> {e.new_value}")
            continue
        text = e.path.read_text()
        if e.old_value not in text:
            if e.new_value in text:
                continue  # idempotent: already rewritten
            raise ValueError(f"{e.path}: expected output_store value not found: {e.old_value}")
        new_text = text.replace(e.old_value, e.new_value)
        tmp = e.path.with_name(e.path.name + ".retok_tmp")
        tmp.write_text(new_text)
        tmp.replace(e.path)  # atomic
        _append_journal(
            journal,
            {
                "op": "config_edit",
                "path": str(e.path),
                "old_value": e.old_value,
                "new_value": e.new_value,
                "result": "applied",
            },
        )
        applied += 1
        print(f"  edited {e.path.name}: output_store re-tokenized")
    return applied


def rollback(journal: Path, dry_run: bool) -> int:
    """Reverse applied journal rows (dir dst -> src, config new -> old), newest first."""
    if not journal.exists():
        raise FileNotFoundError(f"no journal at {journal}")
    with journal.open() as fh:
        rows = [json.loads(line) for line in fh if line.strip()]
    applied_rows = [r for r in rows if r.get("result") == "applied"]
    reversed_count = 0
    for r in reversed(applied_rows):
        if r["op"] == "dir_move":
            src, dst = Path(r["src"]), Path(r["dst"])
            if not dst.exists():
                print(f"  [skip] dir dest gone (already reversed?): {dst}")
                continue
            if src.exists():
                raise RuntimeError(f"cannot reverse dir move: src already exists {src}")
            if dry_run:
                print(f"  [dry-run] reverse move: {dst} -> {src}")
                reversed_count += 1
                continue
            dst.rename(src)
            _append_journal(journal, {"op": "dir_move", "src": str(dst), "dst": str(src), "result": "reversed"})
        elif r["op"] == "config_edit":
            path, old_value, new_value = Path(r["path"]), r["old_value"], r["new_value"]
            text = path.read_text()
            if new_value not in text:
                print(f"  [skip] config already reverted?: {path}")
                continue
            if dry_run:
                print(f"  [dry-run] reverse edit: {path} ({new_value} -> {old_value})")
                reversed_count += 1
                continue
            tmp = path.with_name(path.name + ".retok_tmp")
            tmp.write_text(text.replace(new_value, old_value))
            tmp.replace(path)
            _append_journal(
                journal,
                {
                    "op": "config_edit",
                    "path": str(path),
                    "old_value": new_value,
                    "new_value": old_value,
                    "result": "reversed",
                },
            )
        else:
            raise ValueError(f"unknown journal op {r['op']!r}")
        reversed_count += 1
    return reversed_count


def main(argv: list[str] | None = None) -> int:
    """CLI: dry-run / apply / rollback the ER/mito deconv re-tokenize."""
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--data-root", type=Path, default=DATA_ROOT, help="prediction data root (default: paths.DATA_ROOT)")
    ap.add_argument(
        "--config-root",
        type=Path,
        action="append",
        default=None,
        help="config tree to scan for predict-leaf output_store (repeatable; default: dynacell configs)",
    )
    ap.add_argument("--no-configs", action="store_true", help="skip config edits (dir moves only)")
    ap.add_argument(
        "--organelle", choices=ORGANELLES, action="append", default=None, help="restrict to one organelle (repeatable)"
    )
    ap.add_argument(
        "--skip",
        action="append",
        default=[],
        help="exclude a dir from move + config edit (live-writer guard; repeatable)",
    )
    ap.add_argument(
        "--warn-recent-min", type=int, default=0, help="warn (non-blocking) for planned dirs modified within N minutes"
    )
    ap.add_argument("--journal", type=Path, default=Path("retokenize_deconv.journal.jsonl"), help="journal JSONL path")
    ap.add_argument("--apply", action="store_true", help="execute (default: dry-run preview)")
    ap.add_argument("--rollback", action="store_true", help="reverse the journal (dst -> src, new -> old)")
    args = ap.parse_args(argv)

    dry_run = not args.apply
    if args.rollback:
        n = rollback(args.journal, dry_run)
        print(f"{'[dry-run] would reverse' if dry_run else 'reversed'} {n} op(s); journal {args.journal}")
        return 0

    organelles = tuple(args.organelle) if args.organelle else ORGANELLES
    config_roots = [] if args.no_configs else (args.config_root or [_DEFAULT_CONFIG_ROOT])

    moves = plan_dir_moves(args.data_root, organelles, args.skip)
    edits = plan_config_edits(config_roots, args.data_root, organelles, args.skip)
    pending, already, errors = preflight_moves(moves)

    print(f"data_root: {args.data_root}")
    print(f"organelles: {list(organelles)}   config_roots: {[str(r) for r in config_roots]}")
    print(
        f"dir moves: {len(moves)} planned "
        f"(pending {len(pending)}, already-applied {len(already)}, errors {len(errors)})   "
        f"config edits: {len(edits)}"
    )
    for w in _warn_recent(pending, args.warn_recent_min):
        print(f"  WARN {w}")
    for e in errors:
        print(f"  ERROR {e}")
    if errors:
        print("ABORT: pre-flight errors — nothing performed.")
        return 1

    head = "DRY-RUN (no changes)" if dry_run else "APPLYING"
    print(f"{head} — {len(pending)} dir move(s), {len(edits)} config edit(s):")
    n_moves = apply_moves(pending, args.journal, dry_run)
    n_edits = apply_config_edits(edits, args.journal, dry_run)
    verb = "would move / edit" if dry_run else "moved / edited"
    n_dirs = len(pending) if dry_run else n_moves
    n_cfgs = len(edits) if dry_run else n_edits
    print(
        f"{verb}: {n_dirs} dir(s), {n_cfgs} config(s); {len(already)} dir(s) already applied. journal -> {args.journal}"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
