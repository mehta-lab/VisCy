#!/usr/bin/env python3
"""Generate the DynaCell-lite registry and configs from their production siblings.

DynaCell-lite is a smaller test side of the benchmark for fast model iteration:
A549 keeps all 12 FOVs per condition but 5 of 10 timepoints
(``build_temporal_subset_zarr.py --mode spread --n-timepoints 5``), iPSC keeps 50 of
100 FOVs per GT store (:func:`ipsc_lite_positions`). The lite is a **separately
registered dataset**, never an override of the full one, because every
per-timepoint artifact (segmentation, GT feature cache ``{pos}/t{t}``, focus cache)
is indexed by the store's own ``t``: sharing a cache with the full benchmark would
score frame ``k`` of the subset against frame ``k`` of the full store, and a
T-mismatched write deletes the full benchmark's cache arrays in place.

Isolation is by root, not by vocabulary: every lite artifact lives under
:data:`dynacell.evaluation.paths.LITE_DATA_ROOT`, laid out exactly like
``DATA_ROOT`` (stores, predictions, eval dirs, ``eval_cache``, ``eval_cache_pred``),
so the unchanged path grammar applies with ``data_root=LITE_DATA_ROOT``.

Everything here is **derived** — one production file in, one lite file out:

- ``_manifests/<dataset>-lite/``: test-only manifest (no train store) whose stores
  and ``gt_cache_dir`` are the production paths rebased onto the lite root, plus a
  split listing the lite FOVs. The lite stores must already exist and record the
  production store as their ``temporal_subset.source_store``.
- ``predict_sets/<set>_lite.yml``: the production predict set on the lite dataset.
- ``predict__<set>_lite.yml`` beside each production predict leaf in the roster:
  same checkpoint, overlays and normalization (so a lite prediction of a FOV
  equals the full one), lite predict set, output rebased onto the lite root.
- ``leaf/grouped/<bucket>__lite/eval_grouped.yaml``: the production bucket's roster
  conditions on the lite datasets, lite pred/cache/save paths, no
  ``nuclei_gt_path`` (the lite GT store holds the nuclei), and the metrics the
  lite does not report switched off.

Usage::

    uv run --no-sync python applications/dynacell/tools/generate_lite_benchmark_configs.py --dry-run
    uv run --no-sync python applications/dynacell/tools/generate_lite_benchmark_configs.py
"""

from __future__ import annotations

import argparse
import copy
import sys
from pathlib import Path

import numpy as np
import yaml
from iohub.ngff import open_ome_zarr

from dynacell.evaluation import paths

_APP_ROOT = Path(__file__).resolve().parents[1]
_MANIFEST_ROOT = _APP_ROOT / "src/dynacell/_manifests"
_CONFIG_ROOT = _APP_ROOT / "configs/benchmarks/virtual_staining"
_PREDICT_SETS = _CONFIG_ROOT / "_internal/shared/model/predict_sets"
_GROUPED = _CONFIG_ROOT / "_internal/leaf/grouped"

LITE_SUFFIX = "-lite"
LITE_SET_SUFFIX = "_lite"
IPSC_DATASET = "aics-hipsc"
A549_DATASETS: tuple[str, ...] = tuple(
    f"a549-mantis-{gene}-{cond}" for gene in ("caax", "h2b", "sec61b", "tomm20") for cond in ("mock", "denv", "zikv")
)
IPSC_N_POSITIONS = 50
IPSC_SEED = 0

# Check-F roster: single-pass models only (CELL-Diff is 86 % of predict GPU-h).
ROSTER_MODELS: tuple[str, ...] = (
    "fcmae_vscyto3d_pretrained",
    "fcmae_vscyto3d_scratch",
    "fnet3d_paper",
    "unetvit3d",
)
ROSTER_TRAIN_DIRS: tuple[str, ...] = ("ipsc_confocal", "a549_mantis")
ROSTER_ORGANELLES: tuple[str, ...] = ("nucleus",)
# Predict-leaf train dir -> grouped-bucket train token.
_BUCKET_TRAIN: dict[str, str] = {
    "ipsc_confocal": "ipsc_trained",
    "a549_mantis": "a549_trained",
    "joint_ipsc_confocal_a549_mantis": "joint",
}
# Metrics the lite does not report (none is in the paper's selected set).
LITE_EVAL_OVERRIDES: dict = {
    "compute_microssim": False,
    "feature_metrics": {"compute_fid": False, "compute_prc": False, "compute_mind": False},
}
_HEADER = "# Auto-generated by tools/generate_lite_benchmark_configs.py from {src}. Do not edit; regenerate.\n"


def rebase(path: str | Path, data_root: Path = paths.DATA_ROOT, lite_root: Path = paths.LITE_DATA_ROOT) -> Path:
    """Map a production path onto the lite root, keeping its relative layout.

    Raises
    ------
    ValueError
        If ``path`` is not under ``data_root``.
    """
    return lite_root / Path(path).relative_to(data_root)


def ipsc_lite_positions(names: list[str], n: int = IPSC_N_POSITIONS, seed: int = IPSC_SEED) -> list[str]:
    """Return the lite iPSC positions: a seeded uniform draw of ``n`` from sorted names.

    One fixed draw, recorded before any scoring, so the list cannot be tuned on
    the metrics it is later scored by.
    """
    rng = np.random.default_rng(seed)
    return sorted(rng.choice(sorted(names), n, replace=False).tolist())


def _store_layout(store: Path) -> tuple[dict[str, int], dict]:
    """Return ``({position: T}, temporal_subset zattrs)`` of a store, reading metadata only."""
    with open_ome_zarr(store, mode="r") as plate:
        frames = {name: int(pos.data.shape[0]) for name, pos in plate.positions()}
        subset = dict(plate.zattrs).get("temporal_subset")
    return frames, subset


def _check_lite_store(lite: Path, production: Path) -> tuple[dict[str, int], dict]:
    """Assert ``lite`` exists and was derived from ``production``; return its layout."""
    if not lite.exists():
        raise FileNotFoundError(f"lite store {lite} is missing; build it with build_temporal_subset_zarr.py")
    frames, subset = _store_layout(lite)
    if subset is None or Path(subset["source_store"]) != production:
        raise ValueError(f"{lite} is not a temporal subset of {production} (temporal_subset={subset!r})")
    return frames, subset


def lite_manifest(
    production: dict, data_root: Path = paths.DATA_ROOT, lite_root: Path = paths.LITE_DATA_ROOT
) -> tuple[dict, dict[str, dict]]:
    """Derive a lite manifest and its splits from a production manifest dict.

    Parameters
    ----------
    production : dict
        The production manifest as loaded from YAML.
    data_root, lite_root : Path
        Production and lite roots (arguments for testing).

    Returns
    -------
    tuple[dict, dict[str, dict]]
        The lite manifest and ``{splits relative path: split dict}``.

    Raises
    ------
    ValueError
        If a lite GT store and its segmentation store disagree on positions or
        per-position T, or an iPSC lite store is not the :func:`ipsc_lite_positions`
        draw of its source.
    """
    lite = copy.deepcopy(production)
    name = production["name"]
    lite["name"] = name + LITE_SUFFIX
    lite["description"] = (
        f"DynaCell-lite test subset of {name}, built by build_temporal_subset_zarr.py and registered by "
        f"generate_lite_benchmark_configs.py. Test-only: no train store."
    )
    splits: dict[str, dict] = {}
    for target in lite["targets"].values():
        stores = target["stores"]
        prod_test = Path(stores["test"])
        prod_seg = Path(stores["cell_segmentation"])
        test = rebase(prod_test, data_root, lite_root)
        seg = rebase(prod_seg, data_root, lite_root)
        frames, subset = _check_lite_store(test, prod_test)
        seg_frames, _ = _check_lite_store(seg, prod_seg)
        if frames != seg_frames:
            raise ValueError(f"{test} and {seg} disagree on positions or per-position T")
        if subset["positions"] is not None:
            source_frames, _ = _store_layout(prod_test)
            if sorted(frames) != ipsc_lite_positions(list(source_frames)):
                raise ValueError(f"{test} positions are not the seeded lite draw of {prod_test}")
        target["stores"] = {
            "test": str(test),
            "cell_segmentation": str(seg),
            "gt_cache_dir": str(rebase(stores["gt_cache_dir"], data_root, lite_root)),
        }
        positions = sorted(frames)
        splits[target["splits"]] = {
            "split_version": "1",
            "random_seed": IPSC_SEED if subset["positions"] is not None else 0,
            "source_stores": [str(prod_test)],
            "selection_criteria": {
                "lite_of": name,
                "timepoints": f"{subset['mode']} n_timepoints={subset['n_timepoints']} per position; "
                "the source frames of each position are in the store's .provenance.json sidecar",
                "positions": (
                    "all source positions"
                    if subset["positions"] is None
                    else f"numpy default_rng({IPSC_SEED}).choice(sorted source names, {IPSC_N_POSITIONS}, "
                    "replace=False), sorted"
                ),
            },
            "train": {"count": 0, "fovs": []},
            "test": {"count": len(positions), "fovs": positions},
        }
    return lite, splits


def lite_predict_set(production: dict) -> dict:
    """Point a production predict set at the lite dataset."""
    lite = copy.deepcopy(production)
    lite["benchmark"]["predict_set"] += LITE_SET_SUFFIX
    lite["benchmark"]["dataset_ref"]["dataset"] += LITE_SUFFIX
    return lite


def _writer(leaf: dict) -> dict:
    """Return the single HCSPredictionWriter callback's ``init_args``."""
    writers = [
        cb["init_args"]
        for cb in leaf["trainer"]["callbacks"]
        if cb["class_path"].endswith("prediction_writer.HCSPredictionWriter")
    ]
    if len(writers) != 1:
        raise ValueError(f"expected one HCSPredictionWriter callback, found {len(writers)}")
    return writers[0]


def lite_predict_leaf(production: dict, lite_sets: set[str]) -> dict:
    """Derive a lite predict leaf from its production sibling.

    Raises
    ------
    ValueError
        If the leaf's predict set has no lite variant, or its checkpoint is gone
        (a lite prediction from another checkpoint would not reproduce the full
        benchmark's numbers).
    """
    lite = copy.deepcopy(production)
    set_bases = [b for b in lite["base"] if "/predict_sets/" in b]
    if len(set_bases) != 1:
        raise ValueError(f"expected one predict_sets base, found {set_bases}")
    stem = Path(set_bases[0]).stem
    if stem not in lite_sets:
        raise ValueError(f"predict set {stem!r} has no lite variant")
    lite["base"] = [b.replace(f"/{stem}.yml", f"/{stem}{LITE_SET_SUFFIX}.yml") for b in lite["base"]]
    ckpt = Path(lite["model"]["init_args"]["ckpt_path"])
    if not ckpt.exists():
        raise ValueError(f"checkpoint {ckpt} is gone; re-bake the production leaf first")
    bench = lite["benchmark"]
    bench["predict_set"] += LITE_SET_SUFFIX
    bench["experiment_id"] += "__lite"
    writer = _writer(lite)
    writer["output_store"] = str(rebase(writer["output_store"]))
    lite["launcher"]["run_root"] = str(rebase(lite["launcher"]["run_root"]))
    lite["launcher"]["job_name"] += "_LITE"
    return lite


def lite_grouped_leaf(production: dict, predictions: set[Path]) -> dict:
    """Derive a lite grouped eval leaf, keeping the conditions whose lite prediction is generated.

    Raises
    ------
    ValueError
        If no condition survives.
    """
    lite = {k: copy.deepcopy(v) for k, v in production.items() if k != "conditions"}
    for key, value in LITE_EVAL_OVERRIDES.items():
        if isinstance(value, dict):
            lite.setdefault(key, {}).update(value)
        else:
            lite[key] = value
    conditions = []
    for cond in production["conditions"]:
        pred = cond["io"].get("pred_path")
        if pred is None or rebase(pred) not in predictions:
            continue
        new = copy.deepcopy(cond)
        new["benchmark"]["dataset_ref"]["dataset"] += LITE_SUFFIX
        io = new["io"]
        io["pred_path"] = str(rebase(pred))
        io["pred_cache_dir"] = str(rebase(io["pred_cache_dir"]))
        io.pop("nuclei_gt_path", None)
        new["save"]["save_dir"] = str(rebase(new["save"]["save_dir"]))
        conditions.append(new)
    if not conditions:
        raise ValueError("no condition of the production bucket has a generated lite prediction")
    lite["conditions"] = conditions
    return lite


def _load(path: Path) -> dict:
    return yaml.safe_load(path.read_text())


def _dump(obj: dict, src: Path, package_global: bool = False) -> str:
    head = "# @package _global_\n" if package_global else ""
    rel = src.relative_to(_APP_ROOT)
    return head + _HEADER.format(src=rel) + yaml.safe_dump(obj, sort_keys=False, width=120)


def plan_outputs(organelles: tuple[str, ...], models: tuple[str, ...], train_dirs: tuple[str, ...]) -> dict[Path, str]:
    """Build every lite file in memory: ``{output path: text}``."""
    out: dict[Path, str] = {}
    for name in (*A549_DATASETS, IPSC_DATASET):
        src = _MANIFEST_ROOT / name / "manifest.yaml"
        manifest, splits = lite_manifest(_load(src))
        lite_dir = _MANIFEST_ROOT / manifest["name"]
        out[lite_dir / "manifest.yaml"] = _dump(manifest, src)
        for rel, split in splits.items():
            out[lite_dir / rel] = _dump(split, src)

    lite_sets: set[str] = set()
    for src in sorted(_PREDICT_SETS.glob("*.yml")):
        prod = _load(src)
        dataset = prod.get("benchmark", {}).get("dataset_ref", {}).get("dataset")
        if dataset in (*A549_DATASETS, IPSC_DATASET):
            lite_sets.add(src.stem)
            out[_PREDICT_SETS / f"{src.stem}{LITE_SET_SUFFIX}.yml"] = _dump(lite_predict_set(prod), src)

    predictions: set[Path] = set()
    for organelle in organelles:
        for model in models:
            for train_dir in train_dirs:
                leaf_dir = _CONFIG_ROOT / organelle / model / train_dir
                for src in sorted(leaf_dir.glob("predict__*.yml")):
                    if src.stem.endswith(LITE_SET_SUFFIX):
                        continue
                    prod = _load(src)
                    set_stem = next((Path(b).stem for b in prod.get("base", []) if "/predict_sets/" in b), None)
                    if set_stem not in lite_sets:
                        continue
                    lite = lite_predict_leaf(prod, lite_sets)
                    predictions.add(Path(_writer(lite)["output_store"]))
                    out[leaf_dir / f"{src.stem}{LITE_SET_SUFFIX}.yml"] = _dump(lite, src)

        for train_dir in train_dirs:
            bucket = f"{organelle}_{_BUCKET_TRAIN[train_dir]}"
            src = _GROUPED / bucket / "eval_grouped.yaml"
            lite = lite_grouped_leaf(_load(src), predictions)
            out[_GROUPED / f"{bucket}__lite" / "eval_grouped.yaml"] = _dump(lite, src, package_global=True)
    return out


def main(argv: list[str] | None = None) -> int:
    """CLI: write (or with ``--dry-run`` list) every lite file."""
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--dry-run", action="store_true", help="list the files that would be written")
    ap.add_argument("--organelles", nargs="+", default=list(ROSTER_ORGANELLES))
    ap.add_argument("--models", nargs="+", default=list(ROSTER_MODELS))
    ap.add_argument("--train-dirs", nargs="+", default=list(ROSTER_TRAIN_DIRS), choices=sorted(_BUCKET_TRAIN))
    args = ap.parse_args(argv)
    outputs = plan_outputs(tuple(args.organelles), tuple(args.models), tuple(args.train_dirs))
    for path, text in sorted(outputs.items()):
        status = "unchanged" if path.exists() and path.read_text() == text else "write"
        print(f"{status:9s} {path.relative_to(_APP_ROOT)}")
        if not args.dry_run and status == "write":
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
